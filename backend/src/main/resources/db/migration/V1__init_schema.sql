-- V1: Core Domain Schema for Smart EV Charging Platform

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'ROLE_USER',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE charging_stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(255) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    operational_status VARCHAR(50) NOT NULL DEFAULT 'OPERATIONAL',
    amenities VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE chargers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id BIGINT NOT NULL,
    connector_type VARCHAR(50) NOT NULL,
    max_power_kw DOUBLE PRECISION NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'AVAILABLE',
    price_per_kwh NUMERIC(10, 2) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_charger_station FOREIGN KEY (station_id) REFERENCES charging_stations(id) ON DELETE CASCADE
);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    charger_id BIGINT NOT NULL,
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    expiry_time TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'CONFIRMED',
    idempotency_key VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reservation_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservation_charger FOREIGN KEY (charger_id) REFERENCES chargers(id) ON DELETE RESTRICT
);

CREATE TABLE charging_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT,
    user_id BIGINT NOT NULL,
    charger_id BIGINT NOT NULL,
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time TIMESTAMP WITH TIME ZONE,
    status VARCHAR(50) NOT NULL DEFAULT 'CHARGING',
    energy_consumed_kwh NUMERIC(10, 3) NOT NULL DEFAULT 0.000,
    start_battery_pct DOUBLE PRECISION NOT NULL DEFAULT 20.0,
    current_battery_pct DOUBLE PRECISION NOT NULL DEFAULT 20.0,
    total_cost NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_session_reservation FOREIGN KEY (reservation_id) REFERENCES reservations(id) ON DELETE SET NULL,
    CONSTRAINT fk_session_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_session_charger FOREIGN KEY (charger_id) REFERENCES chargers(id) ON DELETE RESTRICT
);

-- Performance Indexes
CREATE INDEX idx_stations_status ON charging_stations (operational_status);
CREATE INDEX idx_chargers_station ON chargers (station_id);
CREATE INDEX idx_chargers_status ON chargers (status);
CREATE INDEX idx_reservations_user ON reservations (user_id);
CREATE INDEX idx_reservations_charger ON reservations (charger_id);
CREATE INDEX idx_reservations_status ON reservations (status);
CREATE INDEX idx_sessions_user ON charging_sessions (user_id);
CREATE INDEX idx_sessions_charger ON charging_sessions (charger_id);
CREATE INDEX idx_sessions_status ON charging_sessions (status);
